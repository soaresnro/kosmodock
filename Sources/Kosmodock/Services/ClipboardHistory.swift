// The clipboard history widget: what you copy while its tile is on the bar,
// kept on this Mac only, in ~/.config/kosmodock/clipboard (folder 0700,
// files 0600). Anything an app marks as concealed or transient, the way
// password managers do, is skipped.

struct ClipboardOptions: Codable, Equatable, Sendable {
    static let limitRange = 10...1000
    static let daysRange = 1...365

    /// Items kept, besides the pinned ones.
    var limit = 200
    /// Unpinned items are forgotten after this many days.
    var days = 30

    var resolvedLimit: Int { min(max(limit, Self.limitRange.lowerBound), Self.limitRange.upperBound) }
    var resolvedDays: Int { min(max(days, Self.daysRange.lowerBound), Self.daysRange.upperBound) }
}

extension ClipboardOptions {
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let d = ClipboardOptions()
        limit = try c.decode(.limit, or: d.limit)
        days = try c.decode(.days, or: d.days)
    }
}

struct ClipboardItem: Codable, Equatable, Identifiable, Sendable {
    enum Kind: String, Codable, Sendable {
        case text
        case image
        case files
    }

    var id: String
    var kind: Kind
    var text: String?
    var paths: [String]?
    /// PNG files in the history's `images` folder.
    var image: String?
    var thumbnail: String?
    var pixelWidth: Int?
    var pixelHeight: Int?
    /// SHA-256 of the content, so copying the same thing again moves it up.
    var digest: String
    var date: Date
    var isPinned = false

    /// One line for lists and the tile.
    var summary: String {
        switch kind {
        case .text:
            let line = (text ?? "").split(whereSeparator: \.isNewline)
                .lazy.map { $0.trimmingCharacters(in: .whitespaces) }.first { !$0.isEmpty }
            return line ?? ""
        case .image:
            guard let pixelWidth, let pixelHeight else { return L10n.tr("Image") }
            return L10n.tr("Image · %lld × %lld", pixelWidth, pixelHeight)
        case .files:
            let names = (paths ?? []).map { URL(fileURLWithPath: $0).lastPathComponent }
            guard let first = names.first else { return "" }
            return names.count == 1 ? first : L10n.tr("%@ and %lld more", first, names.count - 1)
        }
    }
}

extension ClipboardItem {
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        kind = try c.decode(Kind.self, forKey: .kind)
        text = try c.decodeIfPresent(String.self, forKey: .text)
        paths = try c.decodeIfPresent([String].self, forKey: .paths)
        image = try c.decodeIfPresent(String.self, forKey: .image)
        thumbnail = try c.decodeIfPresent(String.self, forKey: .thumbnail)
        pixelWidth = try c.decodeIfPresent(Int.self, forKey: .pixelWidth)
        pixelHeight = try c.decodeIfPresent(Int.self, forKey: .pixelHeight)
        digest = try c.decode(.digest, or: "")
        date = try c.decode(.date, or: Date())
        isPinned = try c.decode(.isPinned, or: false)
    }
}

// MARK: - What to keep

/// What a pasteboard holds that the history keeps.
enum ClipboardContent: Equatable, Sendable {
    case text(String)
    case files([String])
    /// PNG or TIFF bytes, as the pasteboard had them.
    case image(Data)
}

enum ClipboardFilter {
    /// Markers apps put next to what shouldn't be kept (nspasteboard.org):
    /// password managers mark passwords concealed, and apps mark temporary or
    /// generated copies transient or auto-generated. The last is an older
    /// spelling of the transient marker.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Longer texts and bigger images aren't kept.
    static let maxTextBytes = 1 << 20
    static let maxImageBytes = 30 << 20

    static func shouldIgnore(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { ignoredTypes.contains($0.rawValue) }
    }

    /// Files first (a Finder copy also has their names and icons), then text,
    /// then an image. Nil when nothing is kept.
    static func content(of pasteboard: NSPasteboard) -> ClipboardContent? {
        guard let types = pasteboard.types, !types.isEmpty, !shouldIgnore(types) else { return nil }
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls.map(\.path))
        }
        if let text = pasteboard.string(forType: .string), !text.isBlank {
            return text.utf8.count <= maxTextBytes ? .text(text) : nil
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
            if let data = pasteboard.data(forType: type), data.count <= maxImageBytes { return .image(data) }
        }
        return nil
    }
}

enum ClipboardPolicy {
    static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    static func digest(of content: ClipboardContent) -> String {
        switch content {
        case .text(let text): digest(Data(("text:" + text).utf8))
        case .files(let paths): digest(Data(("files:" + paths.joined(separator: "\n")).utf8))
        case .image(let data): digest(data)
        }
    }

    /// `item` first; the same content copied before is replaced, keeping its pin.
    static func inserting(_ item: ClipboardItem, into items: [ClipboardItem]) -> [ClipboardItem] {
        var item = item
        var rest = items
        if let index = rest.firstIndex(where: { $0.digest == item.digest }) {
            item.isPinned = item.isPinned || rest[index].isPinned
            rest.remove(at: index)
        }
        return [item] + rest
    }

    /// Pinned items always stay. The rest stay while younger than `days` and
    /// among the newest `limit`.
    static func pruned(_ items: [ClipboardItem], limit: Int, days: Int, now: Date) -> (kept: [ClipboardItem], removed: [ClipboardItem]) {
        let cutoff = now.addingTimeInterval(-TimeInterval(days) * 86_400)
        var kept: [ClipboardItem] = []
        var removed: [ClipboardItem] = []
        var unpinned = 0
        for item in items {
            if item.isPinned {
                kept.append(item)
            } else if item.date >= cutoff, unpinned < limit {
                unpinned += 1
                kept.append(item)
            } else {
                removed.append(item)
            }
        }
        return (kept, removed)
    }

    /// Texts and file names containing every word, ignoring case and accents.
    static func search(_ query: String, in items: [ClipboardItem]) -> [ClipboardItem] {
        let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
        guard !words.isEmpty else { return items }
        let options: String.CompareOptions = [.caseInsensitive, .diacriticInsensitive]
        return items.filter { item in
            let haystack = item.kind == .files ? (item.paths ?? []).joined(separator: "\n") : (item.text ?? "")
            return words.allSatisfy { haystack.range(of: $0, options: options) != nil }
        }
    }
}

/// An image as the history keeps it: a PNG and a small thumbnail.
struct ClipboardImage: Sendable {
    var png: Data
    var thumbnail: Data
    var width: Int
    var height: Int

    static let thumbnailSize = 96

    /// Reads PNG or TIFF bytes; nil when ImageIO can't.
    static func make(from data: Data) -> ClipboardImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil)
        else { return nil }
        let isPNG = (CGImageSourceGetType(source) as String?) == UTType.png.identifier
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailSize,
        ]
        guard let png = isPNG ? data : encodePNG(image),
              let small = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary),
              let thumbnail = encodePNG(small)
        else { return nil }
        return ClipboardImage(png: png, thumbnail: thumbnail, width: image.width, height: image.height)
    }

    static func encodePNG(_ image: CGImage) -> Data? {
        let data = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        return CGImageDestinationFinalize(destination) ? data as Data : nil
    }
}

// MARK: - Files

/// `history.json` and `images/` in `directory`, readable only by you.
struct ClipboardStore: Sendable {
    let directory: URL

    static let standard = ClipboardStore(
        directory: ConfigService.defaultFileURL.deletingLastPathComponent().appendingPathComponent("clipboard")
    )

    var historyFile: URL { directory.appendingPathComponent("history.json") }
    var imagesDirectory: URL { directory.appendingPathComponent("images") }

    func imageURL(_ name: String) -> URL { imagesDirectory.appendingPathComponent(name) }

    private static let encoder: JSONEncoder = {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.withoutEscapingSlashes]
        encoder.dateEncodingStrategy = .iso8601
        return encoder
    }()

    func load() -> [ClipboardItem] {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        guard let data = try? Data(contentsOf: historyFile),
              let items = try? decoder.decode([ClipboardItem].self, from: data)
        else { return [] }
        return items
    }

    func save(_ items: [ClipboardItem]) throws {
        try ProtectedFiles.createDirectory(directory)
        try ProtectedFiles.write(Self.encoder.encode(items), to: historyFile)
    }

    func writeImage(_ data: Data, named name: String) throws {
        try ProtectedFiles.createDirectory(directory)
        try ProtectedFiles.createDirectory(imagesDirectory)
        try ProtectedFiles.write(data, to: imageURL(name))
    }

    func removeFiles(of items: [ClipboardItem]) {
        for name in items.flatMap({ [$0.image, $0.thumbnail].compactMap { $0 } }) {
            try? FileManager.default.removeItem(at: imageURL(name))
        }
    }

    func removeAll() {
        try? FileManager.default.removeItem(at: directory)
    }
}

// MARK: - Service

@MainActor
@Observable
final class ClipboardHistory {
    /// Newest first.
    private(set) var items: [ClipboardItem] = []
    private(set) var isEnabled = false

    /// Debug snapshots: never reads the pasteboard or writes files.
    @ObservationIgnored var isPreview = false
    @ObservationIgnored private let store: ClipboardStore
    @ObservationIgnored private let pasteboardProvider: @MainActor () -> NSPasteboard
    @ObservationIgnored private var options = ClipboardOptions()
    @ObservationIgnored private var loop: Task<Void, Never>?
    @ObservationIgnored private var lastChangeCount = 0
    @ObservationIgnored private var lastPrune = Date.distantPast
    @ObservationIgnored private let thumbnails = NSCache<NSString, NSImage>()
    /// Writes happen in order, off the main thread.
    @ObservationIgnored private let io = DispatchQueue(label: "dev.kosmodock.clipboard-history", qos: .utility)

    /// `pasteboard` is read only while enabled, so tests can pass their own.
    init(store: ClipboardStore = .standard, pasteboard: @escaping @MainActor () -> NSPasteboard = { .general }) {
        self.store = store
        pasteboardProvider = pasteboard
    }

    /// Polls the pasteboard's change count every half second while enabled.
    func setEnabled(_ enabled: Bool, options: ClipboardOptions) {
        let optionsChanged = options != self.options
        self.options = options
        let enabled = enabled && !isPreview
        if enabled, optionsChanged, isEnabled { prune(force: true) }
        guard enabled != isEnabled else { return }
        isEnabled = enabled
        loop?.cancel()
        loop = nil
        guard enabled else {
            thumbnails.removeAllObjects()
            if !items.isEmpty { items = [] }
            return
        }
        items = store.load()
        prune(force: true)
        // What's on the pasteboard already was copied before the widget.
        lastChangeCount = pasteboardProvider().changeCount
        loop = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(500))
                self?.poll()
            }
        }
    }

    /// Keeps the pasteboard's content when it changed since the last look.
    func poll(now: Date = Date()) {
        guard isEnabled else { return }
        let pasteboard = pasteboardProvider()
        let count = pasteboard.changeCount
        if count != lastChangeCount {
            lastChangeCount = count
            if let content = ClipboardFilter.content(of: pasteboard) { record(content, at: now) }
        }
        if now.timeIntervalSince(lastPrune) > 3600 { prune(force: false, now: now) }
    }

    private func record(_ content: ClipboardContent, at date: Date) {
        let digest = ClipboardPolicy.digest(of: content)
        let id = UUID().uuidString
        switch content {
        case .text(let text):
            insert(ClipboardItem(id: id, kind: .text, text: text, digest: digest, date: date))
        case .files(let paths):
            insert(ClipboardItem(id: id, kind: .files, paths: paths, digest: digest, date: date))
        case .image(let data):
            // Copied before: only moves up, without decoding it again.
            if var existing = items.first(where: { $0.digest == digest }) {
                existing.date = date
                insert(existing)
                return
            }
            let store = store
            Task.detached(priority: .utility) { [weak self] in
                guard let image = ClipboardImage.make(from: data) else { return }
                let name = "\(id).png", thumbnail = "\(id)-thumb.png"
                do {
                    try store.writeImage(image.png, named: name)
                    try store.writeImage(image.thumbnail, named: thumbnail)
                } catch {
                    return
                }
                let item = ClipboardItem(
                    id: id, kind: .image, image: name, thumbnail: thumbnail,
                    pixelWidth: image.width, pixelHeight: image.height, digest: digest, date: date
                )
                await self?.insert(item)
            }
        }
    }

    private func insert(_ item: ClipboardItem) {
        guard isEnabled else {
            store.removeFiles(of: [item])
            return
        }
        let replaced = items.first { $0.digest == item.digest && $0.id != item.id }
        items = ClipboardPolicy.inserting(item, into: items)
        if let replaced { removeFiles([replaced]) }
        prune(force: true)
    }

    /// Puts the item back on the pasteboard and first in the list.
    func copy(_ item: ClipboardItem) {
        guard !isPreview else { return }
        let pasteboard = pasteboardProvider()
        switch item.kind {
        case .text:
            pasteboard.clearContents()
            pasteboard.setString(item.text ?? "", forType: .string)
        case .files:
            pasteboard.clearContents()
            pasteboard.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            guard let name = item.image, let png = try? Data(contentsOf: store.imageURL(name)) else { return }
            pasteboard.declareTypes([.png, .tiff], owner: nil)
            pasteboard.setData(png, forType: .png)
            if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
        }
        // Our own write: not a new item.
        lastChangeCount = pasteboard.changeCount
        var moved = item
        moved.date = Date()
        items = ClipboardPolicy.inserting(moved, into: items)
        save()
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        prune(force: true)
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        removeFiles([item])
        save()
    }

    /// Forgets everything but the pinned items.
    func clear() {
        let removed = items.filter { !$0.isPinned }
        items.removeAll { !$0.isPinned }
        removeFiles(removed)
        save()
    }

    /// Deletes the whole history, pinned items too: the widget was removed.
    func purge() {
        items = []
        thumbnails.removeAllObjects()
        guard !isPreview else { return }
        let store = store
        io.async { store.removeAll() }
    }

    /// The small image for a list row, read once.
    func thumbnail(for item: ClipboardItem) -> NSImage? {
        guard let name = item.thumbnail else { return nil }
        if let cached = thumbnails.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: store.imageURL(name)) else { return nil }
        thumbnails.setObject(image, forKey: name as NSString)
        return image
    }

    private func prune(force: Bool, now: Date = Date()) {
        guard force || now.timeIntervalSince(lastPrune) > 3600 else { return }
        lastPrune = now
        let result = ClipboardPolicy.pruned(items, limit: options.resolvedLimit, days: options.resolvedDays, now: now)
        if result.kept != items { items = result.kept }
        removeFiles(result.removed)
        save()
    }

    private func removeFiles(_ removed: [ClipboardItem]) {
        guard !removed.isEmpty, !isPreview else { return }
        for item in removed {
            for name in [item.image, item.thumbnail].compactMap({ $0 }) { thumbnails.removeObject(forKey: name as NSString) }
        }
        let store = store
        io.async { store.removeFiles(of: removed) }
    }

    private func save() {
        guard isEnabled, !isPreview else { return }
        let store = store
        let snapshot = items
        io.async { try? store.save(snapshot) }
    }

    /// Waits for the files queued so far (tests).
    func waitForWrites() {
        io.sync {}
    }

    #if DEBUG
    /// Snapshots: sample items, in memory only.
    func injectPreviewItems(_ preview: [ClipboardItem]) {
        isPreview = true
        items = preview
    }
    #endif
}
